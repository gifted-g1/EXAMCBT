const DemoExamTitle = "IFT 211 — Demo Proctored Quiz"

type Options struct {
	BcryptCost int
	DemoExam   bool
	DemoCIDR   string
}

// Run seeds staff, students and (optionally) a DRAFT demo exam.
func Run(db *gorm.DB, opt Options) error {
	if opt.BcryptCost == 0 {
		opt.BcryptCost = 12
	}
	return db.Transaction(func(tx *gorm.DB) error {
		for _, s := range Staff {
			hash, err := bcrypt.GenerateFromPassword([]byte(s.Password), opt.BcryptCost)
			if err != nil {
				return err
			}
			u := models.User{Username: s.Username, PasswordHash: string(hash), FullName: s.FullName, Role: s.Role, IsActive: true}
			if err := tx.Clauses(clause.OnConflict{Columns: []clause.Column{{Name: "username"}}, DoNothing: true}).Create(&u).Error; err != nil {
				return fmt.Errorf("seed staff %s: %w", s.Username, err)
			}
		}
		for _, s := range Students {
			st := models.Student{MatricNo: s.MatricNo, FullName: s.FullName}
			if err := tx.Clauses(clause.OnConflict{Columns: []clause.Column{{Name: "matric_no"}}, DoNothing: true}).Create(&st).Error; err != nil {
				return fmt.Errorf("seed student %s: %w", s.MatricNo, err)
			}
		}
		if opt.DemoExam {
			return seedDemoExam(tx, opt.DemoCIDR)
		}
		return nil
	})
}

func seedDemoExam(tx *gorm.DB, cidr string) error {
	var n int64
	if err := tx.Model(&models.Exam{}).Where("title = ?", DemoExamTitle).Count(&n).Error; err != nil {
		return err
	}
	if n > 0 {
		return nil
	}
	var owner models.User
	if err := tx.Where("username = ?", Staff[0].Username).First(&owner).Error; err != nil {
		return err
	}
	if cidr == "" {
		cidr = "192.168.0.0/16"
	}
	now := time.Now().UTC().Truncate(time.Minute)
	exam := models.Exam{
		Title:       DemoExamTitle,
		Description: "Five-question warm-up used to try the full proctoring flow.",
		CreatedBy:   owner.ID,
		StartsAt:    now,
		EndsAt:      now.Add(2 * time.Hour),
		Status:      models.ExamDraft,
		LANCIDR:     cidr,
	}
	if err := tx.Create(&exam).Error; err != nil {
		return err
	}
	ptr := func(i int) *int { return &i }
	qs := []models.Question{
		{Prompt: "Which layer of the OSI model handles routing?", Options: []string{"Data link", "Network", "Transport", "Session"}, CorrectOption: ptr(1)},
		{Prompt: "What does CIDR stand for?", Options: []string{"Classless Inter-Domain Routing", "Common Internet Data Relay", "Central IP Distribution Registry", "Class Independent Domain Routing"}, CorrectOption: ptr(0)},
		{Prompt: "How many usable host addresses are in a /24 IPv4 subnet?", Options: []string{"256", "255", "254", "128"}, CorrectOption: ptr(2)},
		{Prompt: "Which HTTP status code means 'Locked'?", Options: []string{"403", "409", "423", "451"}, CorrectOption: ptr(2)},
		{Kind: models.QuestionText, Prompt: "In two sentences, explain why an exam server should only listen on the LAN interface."},
	}
	for i := range qs {
		qs[i].ExamID = exam.ID
		qs[i].Position = i + 1
		qs[i].Marks = 1
		if qs[i].Kind == "" {
			qs[i].Kind = models.QuestionMCQ
		}
	}
	return tx.Create(&qs).Error
}

// WriteSQL renders an idempotent MySQL seed script (INSERT IGNORE) with
// freshly bcrypt-hashed passwords.
func WriteSQL(w io.Writer, cost int) error {
	esc := func(s string) string { return strings.ReplaceAll(s, "'", "''") }
	fmt.Fprintln(w, "-- Exam Shield seed data (generated by `go run ./cmd/seed -sql`).")
	fmt.Fprintln(w, "-- Idempotent: INSERT IGNORE skips rows whose unique key already exists,")
	fmt.Fprintln(w, "-- so re-running never duplicates rows or resets changed passwords.")
	fmt.Fprintf(w, "-- Passwords are bcrypt (cost %d) hashes of the mock passwords in README.md.\n\n", cost)
	fmt.Fprintln(w, "START TRANSACTION;")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "INSERT IGNORE INTO users (username, password_hash, full_name, role, is_active) VALUES")
	for i, s := range Staff {
		hash, err := bcrypt.GenerateFromPassword([]byte(s.Password), cost)
		if err != nil {
			return err
		}
		sep := ","
		if i == len(Staff)-1 {
			sep = ";"
		}
		fmt.Fprintf(w, "  ('%s', '%s', '%s', '%s', TRUE)%s\n", s.Username, hash, esc(s.FullName), s.Role, sep)
	}
	fmt.Fprintln(w)
	fmt.Fprintln(w, "INSERT IGNORE INTO students (matric_no, full_name) VALUES")
	for i, s := range Students {
		sep := ","
		if i == len(Students)-1 {
			sep = ";"
		}
		fmt.Fprintf(w, "  ('%s', '%s')%s\n", s.MatricNo, esc(s.FullName), sep)
	}
	fmt.Fprintln(w)
	fmt.Fprintln(w, "COMMIT;")
	return nil
}
